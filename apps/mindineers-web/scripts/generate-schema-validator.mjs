import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import { writeFile } from "node:fs/promises";
// Validate schema structure without compiling user-authored code in the browser.
const ajv = new Ajv({
  strict: false,
  validateFormats: false,
  code: { source: true, esm: true },
});
const validate = ajv.getSchema("http://json-schema.org/draft-07/schema");
const code = standaloneCode(ajv, validate).replace(
  'require("ajv/dist/runtime/equal")',
  "{default: equal}",
);
await writeFile(
  new URL("../src/generated/schema-meta.js", import.meta.url),
  '// Generated by scripts/generate-schema-validator.mjs. Do not edit.\nimport equalModule from "ajv/dist/runtime/equal.js";\nconst equal = typeof equalModule === "function" ? equalModule : equalModule.default;\n' +
    code,
);
